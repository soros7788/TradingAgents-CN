#!/bin/bash
# is_trading_day.sh — 交易日判断 (2026-10-03)
# 用法: is_trading_day.sh [--force]
#   返回 0 = 交易日, 1 = 非交易日
#   --force: 强制返回交易日 (手动放行)

# 2026 年 A 股休市日 (国务院 + 交易所安排)
# 格式: YYYYMMDD
HOLIDAYS=(
    # 元旦
    20260101 20260102 20260103
    # 春节 (初一2/17)
    20260216 20260217 20260218 20260219 20260220 20260221 20260222
    # 清明
    20260404 20260405 20260406
    # 劳动节
    20260501 20260502 20260503 20260504 20260505
    # 端午
    20260619
    # 中秋
    20260925
    # 国庆
    20261001 20261002 20261003 20261004 20261005 20261006 20261007
)

if [ "$1" = "--force" ] || [ "${FORCE:-0}" = "1" ]; then
    exit 0
fi

D8=$(date +%Y%m%d)
DOW=$(date +%u)  # 1=周一 ... 7=周日

# 周末
if [ "$DOW" -ge 6 ]; then
    exit 1
fi

# 法定休市日
for h in "${HOLIDAYS[@]}"; do
    if [ "$D8" = "$h" ]; then
        exit 1
    fi
done

exit 0
